#!/bin/bash
# Build a separate Intel Ventura engine using the installed ToshLLM release's Metal libraries.
set -euo pipefail
export LC_ALL=C

version=0.88.0
llama_commit=b1b770d90d94cad9e9ea5b993bdbc383a522fb28
cmake_version=3.31.8
cmake_sha=d1449f969c54d5c00886d5b643340d493dfb3c81cb39ee29b35453395c11ebf7
local_root="$HOME/.local/share/local-llm"
release="${TOSH_RELEASE_ENGINE:-$local_root/toshllm-engine-$version-macos12-x86_64}"
destination="${TOSH_AVX2_ENGINE:-$local_root/toshllm-engine-$version-macos13-x86_64-avx2}"
work="${TOSH_AVX2_BUILD_ROOT:-}"
jobs="${TOSH_AVX2_JOBS:-3}"

[[ "$(uname -m)" == x86_64 ]]
[[ -f "$release/bin/kernels/fingerprint" ]]
if [[ -e "$destination" ]]; then
    printf 'Destination already exists: %s\n' "$destination" >&2
    exit 1
fi
if [[ -z "$work" ]]; then
    work=$(mktemp -d "${TMPDIR:-/tmp}/tosh-avx2.XXXXXX")
fi
mkdir -p "$work"
work=$(cd "$work" && pwd -P)
printf 'Build files: %s\n' "$work"

download() {
    if [[ ! -f "$2" ]]; then
        curl -fsSL --retry 2 -o "$2.part" "$1"
        mv "$2.part" "$2"
    fi
}

if command -v cmake >/dev/null 2>&1; then
    cmake=$(command -v cmake)
else
    cmake="$work/cmake-$cmake_version-macos-universal/CMake.app/Contents/bin/cmake"
    if [[ ! -x "$cmake" ]]; then
        download "https://github.com/Kitware/CMake/releases/download/v$cmake_version/cmake-$cmake_version-macos-universal.tar.gz" "$work/cmake.tar.gz"
        printf '%s  %s\n' "$cmake_sha" "$work/cmake.tar.gz" | shasum -a 256 -c
        tar -xzf "$work/cmake.tar.gz" -C "$work"
    fi
fi

source_dir="$work/llama.cpp-$llama_commit"
patch_dir="$work/toshllm-$version/patches/llama"
if [[ ! -d "$patch_dir" ]]; then
    download "https://codeload.github.com/engeldlgado/toshllm/tar.gz/refs/tags/v$version" "$work/tosh.tar.gz"
    tar -xzf "$work/tosh.tar.gz" -C "$work"
fi
if [[ ! -f "$source_dir/.tosh-patches-applied" ]]; then
    download "https://codeload.github.com/ggml-org/llama.cpp/tar.gz/$llama_commit" "$work/llama.tar.gz"
    staging=$(mktemp -d "$work/source-stage.XXXXXX")
    tar -xzf "$work/llama.tar.gz" -C "$staging"
    staged_source="$staging/$(basename "$source_dir")"
    find "$patch_dir" -name '*.patch' -print | awk -F/ '{print $NF"\t"$0}' | sort | cut -f2- |
        while IFS= read -r patch_file; do
            (cd "$staged_source" && git apply "$patch_file")
        done
    touch "$staged_source/.tosh-patches-applied"
    if [[ -e "$source_dir" ]]; then
        mv "$source_dir" "$staging/previous-source"
    fi
    mv "$staged_source" "$source_dir"
fi

# SDK 13.3 cannot compile the 14+ architecture property. The existing GPU name
# fallback still selects the aligned reads required by Polaris.
python3 - "$source_dir/ggml/src/ggml-metal/ggml-metal-device.m" <<'PY'
from pathlib import Path
from sys import argv

path = Path(argv[1])
source = path.read_text()
start = "                    if (@available(macOS 14.0, *)) {\n                        const char * arch ="
end = "                    if (!known) {\n                        const char * name = dev->mtl_device.name.UTF8String;"
guard = "#if __MAC_OS_X_VERSION_MAX_ALLOWED >= 140000\n"
if guard + start not in source:
    if source.count(start) != 1 or source.count(end) != 1:
        raise SystemExit("Ventura SDK source anchors have changed")
    path.write_text(source.replace(start, guard + start).replace(end, "#endif\n" + end))
PY

build="$work/build"
if [[ -d "$build/tools/ui/dist" ]]; then
    # A previous configure could have left incomplete downloaded assets.
    # This build serves the release's verified static UI instead.
    stale_ui=$(mktemp -d "$work/stale-ui.XXXXXX")
    mv "$build/tools/ui/dist" "$stale_ui/dist"
fi
"$cmake" -S "$source_dir" -B "$build" \
    -DCMAKE_BUILD_TYPE=Release -DCMAKE_OSX_DEPLOYMENT_TARGET=13.3 \
    -DCMAKE_OSX_ARCHITECTURES=x86_64 -DCMAKE_EXPORT_COMPILE_COMMANDS=ON \
    -DCMAKE_CXX_FLAGS="-DTOSH_VERSION=$version" \
    -DBUILD_SHARED_LIBS=OFF -DLLAMA_OPENSSL=OFF \
    -DLLAMA_BUILD_NUMBER=12359 -DLLAMA_BUILD_COMMIT="${llama_commit:0:9}" \
    -DLLAMA_BUILD_UI=OFF -DLLAMA_USE_PREBUILT_UI=OFF \
    -DLLAMA_BUILD_EXAMPLES=OFF -DLLAMA_BUILD_TESTS=OFF \
    -DGGML_METAL=ON -DGGML_METAL_EMBED_LIBRARY=ON -DTOSH_ENABLE_DYNAMIC_MOE=ON \
    -DGGML_NATIVE=OFF -DGGML_SSE42=ON -DGGML_AVX=ON -DGGML_AVX2=ON \
    -DGGML_FMA=ON -DGGML_F16C=ON -DGGML_BMI2=ON \
    -DGGML_AVX_VNNI=OFF -DGGML_AVX512=OFF
"$cmake" --build "$build" --target llama-server --parallel "$jobs"

quant_object="$build/ggml/src/CMakeFiles/ggml-cpu.dir/ggml-cpu/arch/x86/quants.c.o"
otool -tv "$quant_object" | awk '
    /vpmaddubsw.*%ymm/ && !instruction { instruction = $0 }
    END {
        if (!instruction) exit 1
        print "AVX2 quantization instruction: " instruction
    }
'

embedded="$build/ggml/src/ggml-metal/autogenerated"
while read -r kernel expected; do
    test -f "$release/bin/kernels/$kernel.metallib"
    printf '%s  %s\n' "$expected" "$embedded/ggml-metal-embed-$kernel.metal" | shasum -a 256 -c
done < "$release/bin/kernels/fingerprint"

candidate="$work/candidate/bin"
mkdir -p "$candidate"
install -m 755 "$build/bin/llama-server" "$candidate/llama-server"
ditto "$release/bin/kernels" "$candidate/kernels"
ditto "$release/web-ui" "$work/candidate/web-ui"
otool -l "$candidate/llama-server" | awk '/minos/ { version=$2 } END { print "Minimum macOS: " version; exit version != "13.3" }'
"$candidate/llama-server" --version
devices=$("$candidate/llama-server" --list-devices)
printf '%s\n' "$devices"
printf '%s\n' "$devices" | grep -q 'MTL0: AMD Radeon'

python3 - "$work/candidate" "$destination" <<'PY'
import os
import shutil
import sys
import tempfile
from pathlib import Path

source, target = map(Path, sys.argv[1:])
target.parent.mkdir(parents=True, exist_ok=True)
with tempfile.TemporaryDirectory(dir=target.parent) as staging:
    ready = Path(staging) / "engine"
    shutil.copytree(source, ready)
    os.rename(ready, target)
PY
printf 'AVX2 engine: %s/bin/llama-server\n' "$destination"
if [[ -z "${TOSH_AVX2_BUILD_ROOT:-}" ]]; then
    python3 -c 'import shutil, sys; shutil.rmtree(sys.argv[1])' "$work"
fi
